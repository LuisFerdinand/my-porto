// Writes lib/tech-icons.ts: the brand glyph (a single SVG path) for each technology tag the site uses.
// Only these paths ship to the browser, not the whole simple-icons package. Run: node scripts/gen-tech-icons.mjs
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const brands = {
  "Next.js": "siNextdotjs",
  "Drizzle ORM": "siDrizzle",
  TypeScript: "siTypescript",
  JavaScript: "siJavascript",
  "Tailwind CSS": "siTailwindcss",
  React: "siReact",
  Vue: "siVuedotjs",
  Vite: "siVite",
  HTML: "siHtml5",
  CSS: "siCss",
  "HTML & CSS": "siHtml5",
  "Git & GitHub": "siGithub",
  Vercel: "siVercel",
  "Node.js": "siNodedotjs",
  PHP: "siPhp",
  Laravel: "siLaravel",
  Blade: "siLaravel",
  tRPC: "siTrpc",
  Neon: "siNeon",
  PostgreSQL: "siPostgresql",
  Cloudinary: "siCloudinary",
  "Vercel Blob": "siVercel",
  "Better Auth": "siBetterauth",
  Clerk: "siClerk",
  Resend: "siResend",
  "shadcn/ui": "siShadcnui",
  "Gemini AI": "siGooglegemini",
};

const entries = Object.entries(brands).map(([name, key]) => {
  if (!si[key]) throw new Error(`simple-icons has no ${key}`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(si[key].path)},`;
});

writeFileSync(
  new URL("../lib/tech-icons.ts", import.meta.url),
  `// Generated by scripts/gen-tech-icons.mjs from simple-icons (CC0). Do not edit by hand.
export const BRAND_PATHS: Record<string, string> = {
${entries.join("\n")}
};
`,
);
console.log(`wrote ${entries.length} icons`);
